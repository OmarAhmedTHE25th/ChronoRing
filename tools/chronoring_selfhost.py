#!/usr/bin/env python3
"""ChronoRing Self-Hosting Specializing Compiler.

Reads a high-level `.ddl.json` detector specification and compiles a specialized
zero-overhead C++20 trigger & pipeline engine (`<name>_specialized.hpp` and
`<name>_specialized_main.cpp`) with detector geometry, transport topology, and
trigger cuts constant-folded at compile time via `inline constexpr` / `if constexpr`.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any


VALID_KINDS = {"SNSPD", "TES", "MKID", "SQUID", "IonTrapQubit", "Calorimeter", "Tracker"}
VALID_TRANSPORTS = {"spsc", "pcie_cxl"}


def _validate_identifier(name: str) -> str:
    if not re.match(r"^[a-zA-Z_][a-zA-Z0-9_]*$", name):
        raise ValueError(f"Invalid C++ identifier for detector.name: {name!r}")
    return name


def _is_power_of_two(n: int) -> bool:
    return n >= 2 and (n & (n - 1)) == 0


def _cpp_float(v: float) -> str:
    s = f"{float(v):.9g}"
    if "." not in s and "e" not in s and "E" not in s:
        s += ".0"
    return f"{s}f"


def _cpp_bool(b: bool) -> str:
    return "true" if b else "false"


def _cpp_str(s: str) -> str:
    escaped = s.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def validate_spec(spec: dict[str, Any]) -> None:
    for key in ("detector", "transport", "trigger", "persistence"):
        if key not in spec or not isinstance(spec[key], dict):
            raise ValueError(f"DDL missing required object section: '{key}'")

    det = spec["detector"]
    _validate_identifier(str(det.get("name", "")))
    kind = det.get("kind")
    if kind not in VALID_KINDS:
        raise ValueError(f"Unsupported detector.kind: {kind!r}")
    channels = int(det.get("channels", 0))
    if channels <= 0:
        raise ValueError("detector.channels must be > 0")

    tr = spec["transport"]
    tkind = tr.get("kind", "spsc")
    if tkind not in VALID_TRANSPORTS:
        raise ValueError(f"Unsupported transport.kind: {tkind!r}")
    cap = int(tr.get("ring_capacity", 1024))
    if not _is_power_of_two(cap):
        raise ValueError(f"transport.ring_capacity ({cap}) must be a power of 2 >= 2")


def generate_specialized_header(spec: dict[str, Any]) -> str:
    validate_spec(spec)
    det = spec["detector"]
    name = str(det["name"])
    kind = str(det["kind"])
    channels = int(det["channels"])

    tr = spec["transport"]
    tkind = str(tr.get("kind", "spsc"))
    ring_cap = int(tr.get("ring_capacity", 1024))
    cpu_core = int(tr.get("cpu_core", -1))

    trig = spec["trigger"]
    min_energy = float(trig.get("min_energy_mev", 0.5))
    max_energy = float(trig.get("max_energy_mev", 10000.0))
    max_timing = float(trig.get("max_abs_timing_ps", 250.0))
    max_pileup = float(trig.get("max_pileup_score", 0.5))
    min_mult = int(trig.get("min_multiplicity", 1))
    req_mask = int(trig.get("required_trigger_mask", 0))

    pers = spec["persistence"]
    out_path = str(pers.get("output_path", f"{name}.crng"))
    compress = bool(pers.get("enable_compression", False))
    proj_mask = str(pers.get("projection_mask", "chronoring::kColAll"))

    cal = spec.get("calibration", {})
    gain = float(cal.get("gain_mev_per_unit", 1.0))
    offset = float(cal.get("offset_mev", 0.0))
    walk = float(cal.get("time_walk_ps_per_unit", 0.0))

    return f"""// Auto-generated by tools/chronoring_selfhost.py — DO NOT EDIT MANUALLY.
#pragma once

#include "chronoring/chronoring.hpp"

#include <algorithm>
#include <cmath>
#include <cstddef>
#include <cstdint>
#include <string>

namespace chronoring::selfhost::{name} {{

inline constexpr const char* kDetectorName = {_cpp_str(name)};
inline constexpr const char* kDetectorKind = {_cpp_str(kind)};
inline constexpr std::uint32_t kChannels = {channels}u;
inline constexpr const char* kTransportKind = {_cpp_str(tkind)};
inline constexpr std::size_t kRingCapacity = {ring_cap}u;
inline constexpr int kConsumerCpuCore = {cpu_core};

inline constexpr float kMinEnergyMev = {_cpp_float(min_energy)};
inline constexpr float kMaxEnergyMev = {_cpp_float(max_energy)};
inline constexpr float kMaxAbsTimingPs = {_cpp_float(max_timing)};
inline constexpr float kMaxPileup = {_cpp_float(max_pileup)};
inline constexpr std::uint32_t kRequiredFlags = chronoring::kFlagValid;
inline constexpr std::uint32_t kForbiddenFlags = chronoring::kFlagSaturated | chronoring::kFlagVeto;
inline constexpr std::uint16_t kMinMultiplicity = static_cast<std::uint16_t>({min_mult}u);
inline constexpr std::uint16_t kRequiredTriggerMask = static_cast<std::uint16_t>({req_mask}u);

inline constexpr float kGainMevPerUnit = {_cpp_float(gain)};
inline constexpr float kOffsetMev = {_cpp_float(offset)};
inline constexpr float kTimeWalkPsPerUnit = {_cpp_float(walk)};

inline constexpr std::uint16_t kProjectionMask = static_cast<std::uint16_t>({proj_mask});
inline constexpr bool kEnableCompression = {_cpp_bool(compress)};
inline constexpr const char* kDefaultOutputPath = {_cpp_str(out_path)};

[[nodiscard]] constexpr chronoring::TriggerConfig make_trigger_config() noexcept {{
    chronoring::TriggerConfig cfg{{}};
    cfg.min_energy_mev = kMinEnergyMev;
    cfg.max_energy_mev = kMaxEnergyMev;
    cfg.max_abs_timing_ps = kMaxAbsTimingPs;
    cfg.max_pileup_score = kMaxPileup;
    cfg.required_flags = kRequiredFlags;
    cfg.forbidden_flags = kForbiddenFlags;
    cfg.min_multiplicity = kMinMultiplicity;
    cfg.required_trigger_mask = kRequiredTriggerMask;
    cfg.custom_predicate = nullptr;
    cfg.custom_user_ctx = nullptr;
    return cfg;
}}

[[nodiscard]] inline float calibrate_energy(float raw_units) noexcept {{
    return raw_units * kGainMevPerUnit + kOffsetMev;
}}

[[nodiscard]] inline float walk_correct_timing(float raw_ps, float amplitude_units) noexcept {{
    if constexpr (kTimeWalkPsPerUnit == 0.0f) {{
        (void)amplitude_units;
        return raw_ps;
    }} else {{
        return raw_ps - amplitude_units * kTimeWalkPsPerUnit;
    }}
}}

[[nodiscard]] inline bool validate_channel_geometry(const chronoring::ColumnarPage& page) noexcept {{
    const std::size_t n =
        std::min<std::size_t>(page.header.event_count, chronoring::kColumnarPageEvents);
    for (std::size_t i = 0; i < n; ++i) {{
        if (page.channel_id[i] >= kChannels) {{
            return false;
        }}
    }}
    return true;
}}

// Constant-folded SoA trigger evaluator specialized to {name}.
[[nodiscard]] inline std::size_t eval_specialized(
    const chronoring::ColumnarPage& page,
    std::uint64_t* out_bitmask_words) noexcept {{
    if (out_bitmask_words == nullptr) {{
        return 0;
    }}
    const std::size_t n =
        std::min<std::size_t>(page.header.event_count, chronoring::kColumnarPageEvents);
    const std::size_t words = (n + 63u) / 64u;
    std::size_t kept = 0;

    for (std::size_t w = 0; w < words; ++w) {{
        const std::size_t base = w * 64u;
        const std::size_t lane_count = std::min<std::size_t>(64u, n - base);
        std::uint64_t word = 0u;
        for (std::size_t b = 0; b < lane_count; ++b) {{
            const std::size_t i = base + b;
            const float energy = page.energy_mev[i];
            const float timing = page.timing_ps[i];
            const float pileup = page.pileup_score[i];
            const std::uint32_t flags = page.quality_flags[i];
            const std::uint16_t mult = page.multiplicity[i];

            bool pass = (energy >= kMinEnergyMev && energy <= kMaxEnergyMev) &&
                        (std::fabs(timing) <= kMaxAbsTimingPs) &&
                        (pileup <= kMaxPileup) &&
                        ((flags & kRequiredFlags) == kRequiredFlags) &&
                        ((flags & kForbiddenFlags) == 0u) &&
                        (mult >= kMinMultiplicity);

            if constexpr (kRequiredTriggerMask != 0u) {{
                pass = pass && ((page.trigger_mask[i] & kRequiredTriggerMask) != 0u);
            }}

            if (pass) {{
                word |= (std::uint64_t{{1}} << b);
                ++kept;
            }}
        }}
        out_bitmask_words[w] = word;
    }}
    return kept;
}}

[[nodiscard]] inline chronoring::SoaPipelineConfig build_soa_pipeline_config(
    const std::string& output_path = kDefaultOutputPath) {{
    chronoring::SoaPipelineConfig cfg{{}};
    cfg.output_path = output_path;
    cfg.trigger = make_trigger_config();
    cfg.simd_backend = chronoring::SimdBackend::Auto;
    cfg.consumer_cpu_core = kConsumerCpuCore;
    cfg.projection_mask = kProjectionMask;
    cfg.enable_compression = kEnableCompression;
    return cfg;
}}

}} // namespace chronoring::selfhost::{name}
"""


def generate_specialized_main(spec: dict[str, Any]) -> str:
    name = str(spec["detector"]["name"])
    return f"""// Auto-generated by tools/chronoring_selfhost.py — verification harness.
#include "{name}_specialized.hpp"

#include <array>
#include <cstdlib>
#include <iostream>
#include <memory>
#include <string>

int main(int argc, char** argv) {{
    using namespace chronoring::selfhost::{name};

    const std::string out_path = (argc > 1) ? argv[1] : (std::string(kDetectorName) + "_selfhost.crng");

    auto page = std::make_unique<chronoring::ColumnarPage>();
    chronoring::SoaBatchBuilder builder(page.get());
    builder.bind(page.get());

    const float mid_energy = 0.5f * (kMinEnergyMev + kMaxEnergyMev);
    const float ok_timing = 0.25f * kMaxAbsTimingPs;
    const float ok_pileup = 0.5f * kMaxPileup;
    const std::uint16_t ok_mult = static_cast<std::uint16_t>(kMinMultiplicity + 1u);
    const std::uint16_t ok_tmask = (kRequiredTriggerMask != 0u) ? kRequiredTriggerMask : 1u;

    for (std::size_t i = 0; i < chronoring::kColumnarPageEvents; ++i) {{
        float energy = mid_energy;
        float timing = ok_timing;
        float pileup = ok_pileup;
        std::uint32_t flags = kRequiredFlags;
        std::uint16_t mult = ok_mult;
        const std::uint32_t ch = static_cast<std::uint32_t>(i % kChannels);

        switch (i % 8u) {{
            case 1u:
                energy = kMinEnergyMev * 0.5f;  // fail min energy
                break;
            case 2u:
                energy = kMaxEnergyMev * 1.5f;  // fail max energy
                break;
            case 3u:
                timing = -(kMaxAbsTimingPs + 25.0f);  // fail timing
                break;
            case 4u:
                pileup = kMaxPileup + 0.2f;  // fail pileup
                break;
            case 5u:
                flags = kRequiredFlags | chronoring::kFlagVeto;  // fail forbidden flag
                break;
            case 6u:
                if (kMinMultiplicity > 0u) {{
                    mult = static_cast<std::uint16_t>(kMinMultiplicity - 1u);
                }}
                break;
            default:
                break;
        }}

        if (!builder.append_fields(
                1000000ULL + i * 100ULL,
                static_cast<std::uint64_t>(i + 1u),
                1u,
                ch,
                energy,
                timing,
                pileup,
                flags,
                mult,
                ok_tmask)) {{
            std::cerr << "Failed to append SoA event at i=" << i << "\\n";
            return 2;
        }}
    }}

    if (!validate_channel_geometry(*page)) {{
        std::cerr << "Channel geometry validation failed unexpectedly\\n";
        return 3;
    }}

    std::array<std::uint64_t, chronoring::kColumnarPageEvents / 64u> spec_words{{}};
    std::array<std::uint64_t, chronoring::kColumnarPageEvents / 64u> ref_words{{}};

    const std::size_t spec_kept = eval_specialized(*page, spec_words.data());
    const std::size_t ref_kept = chronoring::evaluate_columnar_page(
        *page, make_trigger_config(), ref_words.data(), chronoring::SimdBackend::Auto);

    if (spec_kept != ref_kept || spec_words != ref_words) {{
        std::cerr << "Bitmask mismatch: spec_kept=" << spec_kept
                  << " ref_kept=" << ref_kept << "\\n";
        return 4;
    }}

    // Verify channel geometry guard catches out-of-range detector channel.
    const std::uint32_t saved_ch = page->channel_id[0];
    page->channel_id[0] = kChannels;
    if (validate_channel_geometry(*page)) {{
        std::cerr << "Geometry guard failed to detect out-of-range channel\\n";
        return 5;
    }}
    page->channel_id[0] = saved_ch;

    // Exercise SoaDataflowPipeline end-to-end with specialized config.
    chronoring::SoaDataflowPipeline pipeline(build_soa_pipeline_config(out_path));
    if (!pipeline.start()) {{
        std::cerr << "SoaDataflowPipeline failed to start\\n";
        return 6;
    }}

    for (int p = 0; p < 2; ++p) {{
        std::size_t pool_idx = 0;
        chronoring::ColumnarPage* slot = pipeline.acquire_input_page(pool_idx);
        if (slot == nullptr) {{
            std::cerr << "Failed to acquire pool slot\\n";
            pipeline.stop();
            return 7;
        }}
        *slot = *page;
        if (!pipeline.submit_input_page(pool_idx)) {{
            std::cerr << "Failed to submit pool slot\\n";
            pipeline.stop();
            return 8;
        }}
    }}

    pipeline.stop();

    if (pipeline.last_status() != chronoring::RingStatus::Ok ||
        pipeline.sink_errors() != 0u ||
        pipeline.consumed_events() != 2u * chronoring::kColumnarPageEvents ||
        pipeline.passed_events() != 2u * spec_kept) {{
        std::cerr << "Pipeline count/status mismatch consumed=" << pipeline.consumed_events()
                  << " passed=" << pipeline.passed_events()
                  << " errors=" << pipeline.sink_errors() << "\\n";
        return 9;
    }}

    const float cal_e = calibrate_energy(10.0f);
    const float walk_t = walk_correct_timing(50.0f, 10.0f);
    (void)cal_e;
    (void)walk_t;

    std::cout << "SELFHOST [" << kDetectorName << "] ok channels=" << kChannels
              << " consumed=" << pipeline.consumed_events()
              << " passed=" << pipeline.passed_events()
              << " pages=" << pipeline.pages_written() << "\\n";
    return 0;
}}
"""


def compile_ddl_to_selfhost(ddl_path: Path, out_dir: Path) -> tuple[Path, Path]:
    spec = json.loads(ddl_path.read_text(encoding="utf-8"))
    validate_spec(spec)
    name = str(spec["detector"]["name"])
    out_dir.mkdir(parents=True, exist_ok=True)
    hpp_path = out_dir / f"{name}_specialized.hpp"
    cpp_path = out_dir / f"{name}_specialized_main.cpp"
    hpp_path.write_text(generate_specialized_header(spec), encoding="utf-8")
    cpp_path.write_text(generate_specialized_main(spec), encoding="utf-8")
    return hpp_path, cpp_path


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="ChronoRing Self-Hosting Specializing Compiler"
    )
    parser.add_argument("ddl", type=Path, help="Path to .ddl.json specification")
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=Path("."),
        help="Output directory for specialized C++20 header and main source",
    )
    args = parser.parse_args(argv)
    hpp_path, cpp_path = compile_ddl_to_selfhost(args.ddl, args.out_dir)
    print(f"Generated specialized engine: {hpp_path} and {cpp_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
