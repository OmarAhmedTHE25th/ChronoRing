#!/usr/bin/env python3
"""ChronoRing Detector Description Language (DDL) Compiler.

Generates a standalone C++20 data-acquisition pipeline header and runner binary
directly from a high-level `.ddl.json` detector specification.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any


QUANTUM_KINDS = {"SNSPD", "TES", "MKID", "SQUID", "IonTrapQubit"}
VALID_KINDS = QUANTUM_KINDS | {"Calorimeter", "Tracker"}
VALID_TRANSPORTS = {"spsc", "pcie_cxl"}


def _validate_identifier(name: str) -> str:
    if not re.match(r"^[a-zA-Z_][a-zA-Z0-9_]*$", name):
        raise ValueError(f"Invalid C++ identifier for detector.name: {name!r}")
    return name


def _is_power_of_two(n: int) -> bool:
    return n >= 2 and (n & (n - 1)) == 0


def _cpp_str(s: str) -> str:
    escaped = s.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def _cpp_bool(b: bool) -> str:
    return "true" if b else "false"


def validate_ddl(spec: dict[str, Any]) -> None:
    for key in ("detector", "transport", "trigger", "persistence"):
        if key not in spec or not isinstance(spec[key], dict):
            raise ValueError(f"DDL missing required object section: '{key}'")

    det = spec["detector"]
    _validate_identifier(str(det.get("name", "")))
    kind = det.get("kind")
    if kind not in VALID_KINDS:
        raise ValueError(f"Unsupported detector.kind: {kind!r}; expected one of {sorted(VALID_KINDS)}")
    channels = int(det.get("channels", 0))
    if channels <= 0:
        raise ValueError("detector.channels must be > 0")

    tr = spec["transport"]
    tkind = tr.get("kind", "spsc")
    if tkind not in VALID_TRANSPORTS:
        raise ValueError(f"Unsupported transport.kind: {tkind!r}")
    cap = int(tr.get("ring_capacity", 1024))
    if not _is_power_of_two(cap):
        raise ValueError(f"transport.ring_capacity ({cap}) must be a power of 2 >= 2")


def generate_header(spec: dict[str, Any]) -> str:
    det = spec["detector"]
    name = det["name"]
    kind = det["kind"]
    channels = int(det["channels"])
    is_quantum = kind in QUANTUM_KINDS

    tr = spec["transport"]
    tkind = tr.get("kind", "spsc")
    ring_cap = int(tr.get("ring_capacity", 1024))
    cpu_core = int(tr.get("cpu_core", -1))

    trig = spec["trigger"]
    min_energy = float(trig.get("min_energy_mev", 0.5))
    max_energy = float(trig.get("max_energy_mev", 10000.0))
    max_timing = float(trig.get("max_abs_timing_ps", 250.0))
    max_pileup = float(trig.get("max_pileup_score", 0.5))
    min_mult = int(trig.get("min_multiplicity", 1))

    pers = spec["persistence"]
    out_path = str(pers.get("output_path", f"{name}.crng"))
    sec_path = str(pers.get("secondary_output_path", ""))
    compress = bool(pers.get("enable_compression", False))
    proj_mask = str(pers.get("projection_mask", "chronoring::kColAll"))

    cal = spec.get("calibration", {})
    gain = float(cal.get("gain_mev_per_unit", 1.0))
    offset = float(cal.get("offset_mev", 0.0))
    walk = float(cal.get("time_walk_ps_per_unit", 0.0))
    nom_temp = float(cal.get("nominal_bath_temp_mk", 100.0))
    max_drift = float(cal.get("max_temp_drift_mk", 10.0))
    max_bias = float(cal.get("max_bias_ua", 100.0))

    lines: list[str] = [
        "// Auto-generated by tools/chronoring_ddl.py — DO NOT EDIT MANUALLY.",
        "#pragma once",
        "",
        '#include "chronoring/chronoring.hpp"',
        "",
        "#include <algorithm>",
        "#include <cstddef>",
        "#include <cstdint>",
        "#include <string>",
        "#include <thread>",
        "#include <vector>",
        "",
        "namespace chronoring::generated {",
        "",
        f"inline chronoring::TriggerConfig make_{name}_trigger_config() noexcept {{",
        "    chronoring::TriggerConfig cfg{};",
        f"    cfg.min_energy_mev = {min_energy:.6f}f;",
        f"    cfg.max_energy_mev = {max_energy:.6f}f;",
        f"    cfg.max_abs_timing_ps = {max_timing:.6f}f;",
        f"    cfg.max_pileup_score = {max_pileup:.6f}f;",
        f"    cfg.min_multiplicity = {min_mult}u;",
        "    cfg.required_flags = chronoring::kFlagValid;",
        "    cfg.forbidden_flags = chronoring::kFlagSaturated | chronoring::kFlagVeto;",
    ]
    if is_quantum:
        lines.append(
            f"    cfg.required_trigger_mask = static_cast<std::uint16_t>(1u << static_cast<unsigned>(chronoring::CryoDetectorKind::{kind}));"
        )
    lines += [
        "    return cfg;",
        "}",
        "",
        f"inline chronoring::PipelineConfig make_{name}_pipeline_config(",
        '    const std::string& out_override = "") {',
        "    chronoring::PipelineConfig cfg{};",
        f"    cfg.output_path = out_override.empty() ? std::string({_cpp_str(out_path)}) : out_override;",
    ]
    if sec_path:
        lines.append(f"    cfg.secondary_output_path = out_override.empty() ? std::string({_cpp_str(sec_path)}) : (out_override + \".bak\");")
    lines += [
        f"    cfg.trigger = make_{name}_trigger_config();",
        f"    cfg.consumer_cpu_core = {cpu_core};",
        f"    cfg.projection_mask = static_cast<std::uint16_t>({proj_mask});",
        f"    cfg.enable_compression = {_cpp_bool(compress)};",
        "    cfg.use_soa_staging = true;",
        "    cfg.adaptive_batching = true;",
        "    return cfg;",
        "}",
        "",
    ]

    if is_quantum:
        lines += [
            f"inline chronoring::QuantumCalibration make_{name}_calibration() noexcept {{",
            "    chronoring::QuantumCalibration cal{};",
            f"    cal.gain_mev_per_unit = {gain:.6f}f;",
            f"    cal.offset_mev = {offset:.6f}f;",
            f"    cal.time_walk_ps_per_unit = {walk:.6f}f;",
            f"    cal.nominal_bath_temp_mk = {nom_temp:.6f}f;",
            f"    cal.max_temp_drift_mk = {max_drift:.6f}f;",
            f"    cal.max_bias_ua = {max_bias:.6f}f;",
            f"    cal.detector_kind = chronoring::CryoDetectorKind::{kind};",
            "    return cal;",
            "}",
            "",
        ]

    lines += [
        f"inline chronoring::PipelineStats run_{name}_daq(",
        "    std::size_t num_events,",
        '    const std::string& out_override = "") {',
        f"    chronoring::TelemetryPipeline pipeline(make_{name}_pipeline_config(out_override));",
        "    if (!pipeline.start()) {",
        "        return pipeline.stats();",
        "    }",
    ]

    if is_quantum:
        lines += [
            f"    const chronoring::QuantumDetectorSource source(make_{name}_calibration());",
            "    auto make_frame = [&](std::size_t seq) -> chronoring::EventFrame {",
            "        chronoring::QuantumEventSample s{};",
            "        s.timestamp_ns = 10000ULL + static_cast<std::uint64_t>(seq) * 25ULL;",
            "        s.sequence_id = static_cast<std::uint64_t>(seq);",
            f"        s.pixel_id = static_cast<std::uint32_t>(seq % {channels}U);",
            "        s.arrival_ps = 15.0f;",
            "        s.pulse_integral = 20.0f;",
            f"        s.bath_temp_mk = {nom_temp:.6f}f;",
            f"        s.coincidence_count = {max(1, min_mult)}u;",
            f"        s.kind = chronoring::CryoDetectorKind::{kind};",
            "        return source.encode(s);",
            "    };",
        ]
    else:
        lines += [
            "    auto make_frame = [&](std::size_t seq) -> chronoring::EventFrame {",
            "        chronoring::EventFrame f{};",
            "        f.timestamp_ns = 10000ULL + static_cast<std::uint64_t>(seq) * 25ULL;",
            "        f.sequence_id = static_cast<std::uint64_t>(seq);",
            f"        f.channel_id = static_cast<std::uint32_t>(seq % {channels}U);",
            f"        f.energy_mev = {max(1.0, min_energy + 10.0):.6f}f;",
            "        f.timing_ps = 10.0f;",
            "        f.pileup_score = 0.05f;",
            "        f.quality_flags = chronoring::kFlagValid | chronoring::kFlagCalibrated;",
            f"        f.multiplicity = {max(1, min_mult)}u;",
            "        return f;",
            "    };",
        ]

    if tkind == "pcie_cxl":
        lines += [
            "    chronoring::PcieCxlRing p2p_ring;",
            f"    if (p2p_ring.allocate_pinned({ring_cap}U) == chronoring::RingStatus::Ok) {{",
            "        chronoring::MockFpgaDmaProducer fpga(p2p_ring.raw_base());",
            "        std::thread fpga_th([&]() {",
            "            std::vector<chronoring::EventFrame> burst(32);",
            "            std::size_t sent = 0;",
            "            while (sent < num_events) {",
            "                const std::size_t chunk = std::min<std::size_t>(burst.size(), num_events - sent);",
            "                for (std::size_t i = 0; i < chunk; ++i) {",
            "                    burst[i] = make_frame(sent + i);",
            "                }",
            "                const std::size_t pushed = fpga.dma_write_burst(burst.data(), chunk);",
            "                sent += pushed;",
            "                if (pushed == 0) {",
            "                    std::this_thread::yield();",
            "                }",
            "            }",
            "            fpga.signal_device_close();",
            "        });",
            "        std::vector<chronoring::EventFrame> pop_buf(32);",
            "        for (;;) {",
            "            const std::size_t n = p2p_ring.try_pop_batch(pop_buf.data(), pop_buf.size());",
            "            if (n > 0) {",
            "                for (std::size_t i = 0; i < n; ++i) {",
            "                    pipeline.submit_wait(pop_buf[i]);",
            "                }",
            "            } else if (p2p_ring.is_device_closed() && p2p_ring.empty()) {",
            "                break;",
            "            } else {",
            "                std::this_thread::yield();",
            "            }",
            "        }",
            "        fpga_th.join();",
            "    }",
        ]
    else:
        lines += [
            "    for (std::size_t i = 0; i < num_events; ++i) {",
            "        pipeline.submit_wait(make_frame(i));",
            "    }",
        ]

    lines += [
        "    pipeline.stop();",
        "    return pipeline.stats();",
        "}",
        "",
        "} // namespace chronoring::generated",
        "",
    ]
    return "\n".join(lines)


def generate_main(spec: dict[str, Any]) -> str:
    det = spec["detector"]
    name = det["name"]
    obs = spec.get("observability", {})
    prom = bool(obs.get("prometheus", True))

    lines: list[str] = [
        "// Auto-generated by tools/chronoring_ddl.py — DO NOT EDIT MANUALLY.",
        f'#include "{name}_daq_chain.hpp"',
        "",
        "#include <cstdlib>",
        "#include <iostream>",
        "#include <string>",
        "",
        "int main(int argc, char** argv) {",
        "    std::size_t num_events = 4096;",
        "    std::string out_override;",
        "    if (argc >= 2) {",
        "        num_events = static_cast<std::size_t>(std::strtoull(argv[1], nullptr, 10));",
        "    }",
        "    if (argc >= 3) {",
        "        out_override = argv[2];",
        "    }",
        f"    const chronoring::PipelineStats stats = chronoring::generated::run_{name}_daq(num_events, out_override);",
        f'    std::cout << "DDL DAQ [{name}] status=" << chronoring::status_string(stats.last_status)',
        '              << " consumed=" << stats.consumed_events',
        '              << " passed=" << stats.passed_events',
        '              << " pages=" << stats.pages_written << "\\n";',
    ]
    if prom:
        lines.append("    std::cout << chronoring::to_prometheus_text(stats);")
    lines += [
        "    return (stats.last_status == chronoring::RingStatus::Ok && stats.sink_errors == 0) ? 0 : 1;",
        "}",
        "",
    ]
    return "\n".join(lines)


def compile_ddl(ddl_path: Path, out_dir: Path) -> tuple[Path, Path]:
    spec = json.loads(ddl_path.read_text(encoding="utf-8"))
    validate_ddl(spec)
    name = spec["detector"]["name"]

    out_dir.mkdir(parents=True, exist_ok=True)
    hdr_path = out_dir / f"{name}_daq_chain.hpp"
    cpp_path = out_dir / f"{name}_daq_main.cpp"

    hdr_path.write_text(generate_header(spec), encoding="utf-8")
    cpp_path.write_text(generate_main(spec), encoding="utf-8")
    return hdr_path, cpp_path


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate C++20 DAQ pipeline from ChronoRing DDL JSON")
    parser.add_argument("ddl_file", type=Path, help="Input .ddl.json specification")
    parser.add_argument("--out-dir", type=Path, required=True, help="Output directory for generated C++20 files")
    args = parser.parse_args(argv)

    hdr, cpp = compile_ddl(args.ddl_file, args.out_dir)
    print(f"Generated {hdr} and {cpp}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
